async function importar() {
  const lines = csvData.trim().split('\n');

  for (let i = 1; i < lines.length; i++) {
    const fields = lines[i].split(';');
    const placa = fields[0]?.trim();
    if (!placa) continue;

    const payload = {
      placa: placa,
      modelo: fields[1]?.trim() || '',
      anoModelo: fields[2]?.trim() || '',
      anoFabricacao: fields[3]?.trim() || '',
      capacidade: fields[4]?.trim() || '',
      renavam: fields[5]?.trim() || '',
      pesoBrutoTotal: fields[6]?.trim() || '',
      especieTipo: fields[7]?.trim() || '',
      chassi: fields[8]?.trim() || '',
      categoria: fields[9]?.trim() || '',
      carroceria: fields[10]?.trim() || '',
      potenciaCilindrada: fields[11]?.trim() || '',
      motor: fields[12]?.trim() || '',
      cmt: fields[13]?.trim() || '',
      eixos: fields[14]?.trim() || '',
      lotacao: fields[15]?.trim() || '',
      nomeProprietario: fields[16]?.trim() || '',
      cpfCnpj: fields[17]?.trim() || '',
      corPredominante: fields[18]?.trim() || '',
      combustivel: fields[19]?.trim() || '',
      kmRevisao: fields[20]?.trim() ? parseFloat(fields[20].trim().replace(',', '.')) : 0,
      intervaloRevisao: fields[21]?.trim() ? parseFloat(fields[21].trim().replace('.', '')) : 50000
    };

    try {
      const response = await fetch('http://localhost:3000/api/veiculos', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
      });
      if (!response.ok) {
        console.log(`Erro ao cadastrar ${placa}: ${await response.text()}`);
      } else {
        console.log(`Atualizado ${placa} com sucesso.`);
      }
    } catch (e) {
      console.log(`Exceção ao cadastrar ${placa}: ${e.message}`);
    }
  }
}

